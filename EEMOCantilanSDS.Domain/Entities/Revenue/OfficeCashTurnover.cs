using EEMOCantilanSDS.Domain.Common;

namespace EEMOCantilanSDS.Domain.Entities.Revenue;

public enum OfficeCashTurnoverStatus
{
    Recorded = 1,
    Voided = 2
}

/// <summary>
/// Cash the Head/Office collected directly (canonical Collections with no collector) and turned over, with a system-generated internal reference and an
/// optional supporting-document reference the Head entered. It is not a revenue event, a bank deposit or a Treasury acknowledgment: it creates no Collection or line and never
/// changes what any report counts as income. It covers whole, already-posted Office Collections; each is actively covered by at most
/// one turnover. The expected amount is derived from the covered Collections net of their corrections and frozen here; the turned-over
/// amount is what was handed over; the difference (shortfall positive, excess negative) stays visible and is never absorbed by
/// adjusting a Collection. Append-only: a mistake is voided with a reason, which frees its coverage and keeps its history.
/// </summary>
public sealed class OfficeCashTurnover : BaseEntity, IMunicipalityOwned
{
    public Guid MunicipalityId { get; private set; }
    public DateOnly TurnoverDate { get; private set; }
    public DateOnly PeriodFrom { get; private set; }
    public DateOnly PeriodTo { get; private set; }
    public decimal ExpectedAmount { get; private set; }
    public decimal TurnedOverAmount { get; private set; }

    /// <summary>Expected less turned over. Positive is a shortfall, negative an excess; either needs review and is never zero-filled.</summary>
    public decimal DifferenceAmount { get; private set; }

    /// <summary>Year of the turnover date; with the sequence-assigned number it makes the internal reference unique per tenant and year.</summary>
    public int ReferenceYear { get; private set; }

    /// <summary>Assigned by the database sequence on insert, so concurrent turnovers can never share one.</summary>
    public long ReferenceNumber { get; private set; }

    /// <summary>StallTrack's own internal turnover reference (OCT-year-number), generated by the database. Not an OR, Treasury or bank deposit reference.</summary>
    public string ReferenceCode { get; private set; } = string.Empty;

    /// <summary>An optional external supporting-document reference as entered (slip, receipt or voucher number). Never generated or verified by StallTrack.</summary>
    public string? Reference { get; private set; }

    /// <summary>The person who handed the cash over, as entered.</summary>
    public string TurnedOverBy { get; private set; } = string.Empty;
    public string? Remarks { get; private set; }
    public OfficeCashTurnoverStatus Status { get; private set; }
    public string? VoidReason { get; private set; }
    public DateTime? VoidedAtUtc { get; private set; }
    public string? VoidedBy { get; private set; }
    public string? VoidedByActorId { get; private set; }

    /// <summary>Durable idempotency identity: a retry with the same id and intent returns this turnover, never a second one.</summary>
    public Guid ClientOperationId { get; private set; }
    public string IntentFingerprint { get; private set; } = string.Empty;
    public DateTime RecordedAtUtc { get; private set; }
    public string RecordedBy { get; private set; } = string.Empty;
    public string RecordedByActorId { get; private set; } = string.Empty;
    public int CollectionCount { get; private set; }

    private OfficeCashTurnover() { }

    public bool NeedsReview => Status == OfficeCashTurnoverStatus.Recorded && DifferenceAmount != 0m;

    public static OfficeCashTurnover Record(
        Guid municipalityId, DateOnly turnoverDate, DateOnly periodFrom, DateOnly periodTo,
        decimal expectedAmount, decimal turnedOverAmount, int collectionCount,
        string? reference, string turnedOverBy, string? remarks,
        Guid clientOperationId, string intentFingerprint, string recordedBy, string recordedByActorId, DateTime recordedAtUtc)
    {
        if (municipalityId == Guid.Empty) throw new ArgumentException("A tenant is required.");
        if (periodTo < periodFrom) throw new ArgumentException("The coverage period cannot end before it begins.");
        if (turnoverDate < periodTo) throw new ArgumentException("A turnover cannot be dated before the cash it covers was collected.");
        if (collectionCount <= 0 || expectedAmount <= 0m)
            throw new ArgumentException("A turnover covers at least one collection with money to account for.");
        if (turnedOverAmount <= 0m || decimal.Round(turnedOverAmount, 2) != turnedOverAmount)
            throw new ArgumentException("The turned-over amount must be a positive amount in whole centavos.", nameof(turnedOverAmount));
        if (clientOperationId == Guid.Empty || string.IsNullOrWhiteSpace(intentFingerprint))
            throw new ArgumentException("A durable operation identity is required.");
        if (string.IsNullOrWhiteSpace(recordedBy) || string.IsNullOrWhiteSpace(recordedByActorId))
            throw new ArgumentException("The recording actor is required.");
        if (recordedAtUtc.Kind != DateTimeKind.Utc) throw new ArgumentException("The recording time must be UTC.", nameof(recordedAtUtc));
        var evidence = string.IsNullOrWhiteSpace(reference) ? null : reference.Trim();
        var handedBy = turnedOverBy?.Trim();
        var remark = string.IsNullOrWhiteSpace(remarks) ? null : remarks.Trim();
        if (evidence?.Length > 100)
            throw new ArgumentException("A supporting reference of up to 100 characters is allowed.", nameof(reference));
        if (string.IsNullOrEmpty(handedBy) || handedBy.Length > 150)
            throw new ArgumentException("The person who turned over the cash is required.", nameof(turnedOverBy));
        if (remark?.Length > 500) throw new ArgumentException("The remarks are too long.", nameof(remarks));
        if (expectedAmount != turnedOverAmount && remark is null)
            throw new ArgumentException("A shortfall or excess needs an explanation in the remarks.", nameof(remarks));
        return new OfficeCashTurnover
        {
            Id = Guid.NewGuid(), MunicipalityId = municipalityId, TurnoverDate = turnoverDate, ReferenceYear = turnoverDate.Year, PeriodFrom = periodFrom, PeriodTo = periodTo,
            ExpectedAmount = expectedAmount, TurnedOverAmount = turnedOverAmount, DifferenceAmount = expectedAmount - turnedOverAmount,
            Reference = evidence, TurnedOverBy = handedBy, Remarks = remark, Status = OfficeCashTurnoverStatus.Recorded,
            ClientOperationId = clientOperationId, IntentFingerprint = intentFingerprint, RecordedAtUtc = recordedAtUtc,
            RecordedBy = recordedBy.Trim(), RecordedByActorId = recordedByActorId.Trim(), CollectionCount = collectionCount
        };
    }

    public void Void(string reason, string actor, string actorId, DateTime voidedAtUtc)
    {
        if (Status == OfficeCashTurnoverStatus.Voided) throw new InvalidOperationException("This turnover is already voided.");
        if (string.IsNullOrWhiteSpace(reason) || reason.Trim().Length > 300)
            throw new ArgumentException("A reason of up to 300 characters is required.", nameof(reason));
        if (string.IsNullOrWhiteSpace(actor) || string.IsNullOrWhiteSpace(actorId)) throw new ArgumentException("The voiding actor is required.");
        if (voidedAtUtc.Kind != DateTimeKind.Utc) throw new ArgumentException("The void time must be UTC.", nameof(voidedAtUtc));
        Status = OfficeCashTurnoverStatus.Voided;
        VoidReason = reason.Trim();
        VoidedBy = actor.Trim();
        VoidedByActorId = actorId.Trim();
        VoidedAtUtc = voidedAtUtc;
    }
}

/// <summary>One Office Collection covered by a turnover, with the net amount it contributed and who originally collected it. Active while the turnover stands.</summary>
public sealed class OfficeCashTurnoverCoverage : BaseEntity, IMunicipalityOwned
{
    public Guid MunicipalityId { get; private set; }
    public Guid TurnoverId { get; private set; }
    public Guid CollectionId { get; private set; }
    public decimal CoveredAmount { get; private set; }

    /// <summary>The Collection's own recording actor, copied when covered so the original collector-of-record stays visible.</summary>
    public string OriginalActorId { get; private set; } = string.Empty;
    public string OriginalActorName { get; private set; } = string.Empty;

    /// <summary>False only after the turnover is voided; the partial unique index allows one active coverage per Collection.</summary>
    public bool IsActive { get; private set; }

    private OfficeCashTurnoverCoverage() { }

    public static OfficeCashTurnoverCoverage Cover(Guid municipalityId, Guid turnoverId, Guid collectionId, decimal coveredAmount,
        string originalActorId, string originalActorName)
    {
        if (municipalityId == Guid.Empty || turnoverId == Guid.Empty || collectionId == Guid.Empty)
            throw new ArgumentException("A tenant, turnover and collection are required.");
        if (coveredAmount <= 0m) throw new ArgumentException("Only a collection with money to account for can be covered.", nameof(coveredAmount));
        if (string.IsNullOrWhiteSpace(originalActorId) || string.IsNullOrWhiteSpace(originalActorName))
            throw new ArgumentException("The original recording actor is required.");
        return new OfficeCashTurnoverCoverage
        {
            Id = Guid.NewGuid(), MunicipalityId = municipalityId, TurnoverId = turnoverId, CollectionId = collectionId,
            CoveredAmount = coveredAmount, OriginalActorId = originalActorId.Trim(), OriginalActorName = originalActorName.Trim(), IsActive = true
        };
    }

    public void Release() => IsActive = false;
}
